package javax.management;

/**
 * STUB of {@code javax.management.ReflectionException}.
 */
public class ReflectionException extends Exception {

    public ReflectionException() {
        super();
    }

    public ReflectionException(Exception target) {
        super(target);
    }

    public ReflectionException(Exception target, String message) {
        super(message, target);
    }
}
